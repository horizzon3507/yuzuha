export type YuzuhaErrorCode = (typeof YUZUHA_ERROR_CODES)[number];

export class YuzuhaError extends Error {
  constructor(public readonly code: YuzuhaErrorCode | (string & {}), message: string, options?: ErrorOptions) {
    super(message, options);
    this.name = 'YuzuhaError';
  }
}

